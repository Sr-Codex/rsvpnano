#!/usr/bin/env python3
"""Generate the Lume Nano boot logo masks (src/ui/Logo.generated.h).

Same format as tools/generate_logo.js (246x105, two 4-bit alpha masks, run-length
encoded as (count << 4) | alpha with count <= 4095):
  - foreground: static "LUME" / "nano" wordmark (UI font: Atkinson Hyperlegible)
  - accent:     the flame, which ui::modern::logo() pulses while loading

Usage:
  python3 tools/generate_lume_logo.py            # write src/ui/Logo.generated.h
  python3 tools/generate_lume_logo.py --preview out.png [--header path.h]
"""
from __future__ import annotations

import argparse
import math
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "third_party/atkinson-hyperlegible/AtkinsonHyperlegible-Regular.ttf"
OUT = ROOT / "src/ui/Logo.generated.h"
W, H, SS = 246, 105, 4  # final size and supersampling factor


def flame_polygon(cx: float, base: float, width: float, height: float, lean: float, steps: int = 240):
    """Teardrop flame: round bottom, pointed tip, slightly leaning tip."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        x = math.sin(t) * math.sin(t / 2) ** 1.6       # 0 at the tip (t=0), widest low
        y = (math.cos(t) + 1) / 2                        # 1 at tip, 0 at bottom
        tip = y ** 2.2
        px = cx + x * width / 2 + lean * tip * width
        py = base - y * height
        pts.append((px, py))
    return pts


def draw_layers():
    fg = Image.new("L", (W * SS, H * SS), 0)
    ac = Image.new("L", (W * SS, H * SS), 0)
    # --- flame (accent): outer teardrop with an inner cut-out core ---------------
    d = ImageDraw.Draw(ac)
    fx, fbase = 30 * SS, 86 * SS
    d.polygon(flame_polygon(fx, fbase, 44 * SS, 72 * SS, 0.14), fill=255)
    d.polygon(flame_polygon(fx + 1 * SS, fbase - 5 * SS, 16 * SS, 28 * SS, 0.20), fill=0)
    # --- wordmark (foreground) ----------------------------------------------------
    d = ImageDraw.Draw(fg)
    big = ImageFont.truetype(str(FONT), 58 * SS)
    small = ImageFont.truetype(str(FONT), 24 * SS)

    def spaced(text, font, x, y, tracking):
        for ch in text:
            d.text((x, y), ch, font=font, fill=255)
            x += font.getlength(ch) + tracking
        return x

    spaced("LUME", big, 64 * SS, 6 * SS, 6 * SS)
    spaced("nano", small, 67 * SS, 68 * SS, 11 * SS)
    down = lambda im: im.resize((W, H), Image.Resampling.LANCZOS)
    return down(fg), down(ac)


def pixels(im: Image.Image) -> list[int]:
    return list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())


def encode(mask: Image.Image) -> list[int]:
    runs, last, count = [], -1, 0
    for a in pixels(mask):
        alpha = round(a / 17)
        if alpha == last and count < 4095:
            count += 1
        else:
            if count:
                runs.append((count << 4) | last)
            last, count = alpha, 1
    if count:
        runs.append((count << 4) | last)
    return runs


def decode(runs: list[int]) -> Image.Image:
    px = []
    for r in runs:
        px += [(r & 15) * 17] * (r >> 4)
    assert len(px) == W * H, (len(px), W * H)
    im = Image.new("L", (W, H))
    im.putdata(px)
    return im


def header(fg_runs, ac_runs) -> str:
    out = ["// Generated by tools/generate_lume_logo.py (Lume Nano boot logo).",
           "#pragma once", "#include <cstdint>", "namespace ui::logo {",
           f"inline constexpr int width={W}, height={H};"]
    for name, runs in (("foreground", fg_runs), ("accent", ac_runs)):
        out.append(f"inline constexpr uint16_t {name}[]{{")
        for i in range(0, len(runs), 18):
            out.append(" " + ",".join(f"0x{n:x}" for n in runs[i:i + 18]) + ",")
        out.append("};")
    out.append("}")
    return "\n".join(out) + "\n"


def parse_header(text: str):
    blocks = dict(re.findall(r"uint16_t (\w+)\[\]\{([^}]*)\}", text))
    return [[int(x, 16) for x in re.findall(r"0x[0-9a-f]+", blocks[k])] for k in ("foreground", "accent")]


def preview(fg: Image.Image, ac: Image.Image, path: Path, scale: int = 2):
    bg, fgc, acc = (17, 19, 19), (236, 236, 230), (253, 111, 66)
    img = Image.new("RGB", (W, H), bg)
    img.paste(Image.new("RGB", (W, H), fgc), mask=fg)
    img.paste(Image.new("RGB", (W, H), acc), mask=ac)
    img.resize((W * scale, H * scale), Image.Resampling.NEAREST).save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path)
    ap.add_argument("--header", type=Path, help="preview an existing header instead of generating")
    a = ap.parse_args()
    if a.header:
        fg_runs, ac_runs = parse_header(a.header.read_text())
    else:
        fg, ac = draw_layers()
        fg_runs, ac_runs = encode(fg), encode(ac)
        # Round-trip check: what the firmware decodes equals what we quantized.
        assert pixels(decode(fg_runs)) == [round(v / 17) * 17 for v in pixels(fg)]
        assert pixels(decode(ac_runs)) == [round(v / 17) * 17 for v in pixels(ac)]
    if a.preview:
        preview(decode(fg_runs), decode(ac_runs), a.preview)
        print(f"preview -> {a.preview}")
    else:
        OUT.write_text(header(fg_runs, ac_runs))
        print(f"{OUT.relative_to(ROOT)}: foreground {len(fg_runs)} runs, accent {len(ac_runs)} runs")


if __name__ == "__main__":
    main()
